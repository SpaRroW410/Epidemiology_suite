# Shinylive spike, stage 2 (ROADMAP item 15): assemble a Shinylive app directory from the
# package sources. Usage: Rscript tools/webr-spike/make_app.R <out_dir> [full|light]
#   full  - library() every runtime import (what the package needs today)
#   app   - attach only shiny and bslib (what the package does); the rest is found by the pkg:: scan
#   light - library() only shiny, bslib, pwr, survival. (Shinylive's dependency scan also finds
#           every pkg:: reference in R/, so the same packages are still bundled and downloaded;
#           the variant only changes what is attached at start-up.)
#   full-A+B - full minus the named packages (for bisecting a loading failure)
#   only-A+B - shiny, bslib and the named packages only
args <- commandArgs(trailingOnly = TRUE)
out <- args[1]; variant <- if (length(args) >= 2) args[2] else "full"
unlink(out, recursive = TRUE); dir.create(file.path(out, "R"), recursive = TRUE)
file.copy(list.files("R", full.names = TRUE), file.path(out, "R"))

desc <- read.dcf("DESCRIPTION", fields = "Imports")[1, 1]
imports <- trimws(sub("\\s*\\(.*$", "", strsplit(desc, ",")[[1]]))
imports <- setdiff(imports[nzchar(imports)], c("graphics", "stats", "utils"))
pkgs <- if (variant == "app") {
  # what the package itself attaches: shiny (NAMESPACE import) and bslib (importFrom); every other package is
  # called with pkg:: and is found by shinylive's static scan, so attaching it is not needed
  c("shiny", "bslib")
} else if (variant == "light") {
  c("shiny", "bslib", "pwr", "survival")
} else if (grepl("^only-", variant)) {
  c("shiny", "bslib", strsplit(sub("^only-", "", variant), "+", fixed = TRUE)[[1]])
} else if (grepl("^full-", variant)) {
  setdiff(imports, strsplit(sub("^full-", "", variant), "+", fixed = TRUE)[[1]])
} else imports

lines <- c(
  "# generated by tools/webr-spike/make_app.R",
  vapply(pkgs, function(p) sprintf("try(suppressPackageStartupMessages(library(%s)), silent = TRUE)", p), ""),
  "for (f in sort(list.files('R', pattern = '[.]R$', full.names = TRUE))) {",
  "  r <- try(source(f, local = FALSE), silent = TRUE)",
  "  if (inherits(r, 'try-error')) message('SOURCE FAILED: ', f, ': ', conditionMessage(attr(r, 'condition')))",
  "}",
  "epidemiologicasuite_app()"
)
writeLines(lines, file.path(out, "app.R"))
cat(sprintf("Wrote %s (%s variant, %d library() calls, %d R files)\n", out, variant, length(pkgs), length(list.files(file.path(out, "R")))))
