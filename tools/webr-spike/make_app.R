# Shinylive spike, stage 2 (ROADMAP item 15): assemble a Shinylive app directory from the
# package sources. Usage: Rscript tools/webr-spike/make_app.R <out_dir> [full|light]
#   full  - library() every runtime import (what the package needs today)
#   light - library() only shiny, bslib, pwr, survival. (Shinylive's dependency scan also finds
#           every pkg:: reference in R/, so the same packages are still bundled and downloaded;
#           the variant only changes what is attached at start-up.)
#   probe - like full, but each library() call is timed and reported, to find which one fails
# The package is not installed in the browser; its R/ files are sourced into the global
# environment, so NAMESPACE importFrom() is replaced by attached packages. This is good enough
# to answer "does it boot and does a calculation run"; a real build would ship the package as a
# wasm binary.
args <- commandArgs(trailingOnly = TRUE)
out <- args[1]; variant <- if (length(args) >= 2) args[2] else "full"
unlink(out, recursive = TRUE); dir.create(file.path(out, "R"), recursive = TRUE)
file.copy(list.files("R", full.names = TRUE), file.path(out, "R"))

desc <- read.dcf("DESCRIPTION", fields = "Imports")[1, 1]
imports <- trimws(sub("\\s*\\(.*$", "", strsplit(desc, ",")[[1]]))
imports <- setdiff(imports[nzchar(imports)], c("graphics", "stats", "utils"))
pkgs <- if (variant == "light") c("shiny", "bslib", "pwr", "survival") else imports

# bslib::font_google() downloads the font file when the page is rendered; the browser build has no
# working internet client for that (the first spike run failed exactly there), so the spike replaces it
# with a font stack. This is a spike-only patch; the real app would need the same change to run offline.
f <- file.path(out, "R", "run_app.R")
txt <- readLines(f)
txt <- gsub('font_google\\("Source Serif 4"\\)', 'font_collection("Georgia", "Times New Roman", "serif")', txt)
writeLines(txt, f)

load_lines <- if (variant == "probe") {
  c("for (p in c(%s)) {",
    "  t0 <- Sys.time()",
    "  ok <- tryCatch({ suppressPackageStartupMessages(library(p, character.only = TRUE)); 'ok' }, error = function(e) paste('FAILED:', conditionMessage(e)))",
    "  message(sprintf('LOAD %%s: %%s (%%.1f s)', p, ok, as.numeric(Sys.time() - t0, units = 'secs')))",
    "}")
} else NULL
lines <- c(
  "# generated by tools/webr-spike/make_app.R",
  if (variant == "probe") {
    # literal library() calls are kept (inside a never-run branch) so the export scan bundles them
    c("if (FALSE) {", vapply(pkgs, function(p) sprintf("  library(%s)", p), ""), "}",
      sprintf(paste(load_lines, collapse = "\n"), paste(sprintf("'%s'", pkgs), collapse = ", ")))
  } else vapply(pkgs, function(p) sprintf("try(suppressPackageStartupMessages(library(%s)), silent = TRUE)", p), ""),
  "for (f in sort(list.files('R', pattern = '[.]R$', full.names = TRUE))) {",
  "  r <- try(source(f, local = FALSE), silent = TRUE)",
  "  if (inherits(r, 'try-error')) message('SOURCE FAILED: ', f, ': ', conditionMessage(attr(r, 'condition')))",
  "}",
  "epidemiologicasuite_app()"
)
writeLines(lines, file.path(out, "app.R"))
cat(sprintf("Wrote %s (%s variant, %d library() calls, %d R files)\n", out, variant, length(pkgs), length(list.files(file.path(out, "R")))))
