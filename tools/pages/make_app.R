# Assemble the Shinylive (WebAssembly) app directory published on GitHub Pages (ROADMAP item 15 / hosting).
# Usage: Rscript tools/pages/make_app.R <out_dir>
# The app is the package's own R/ directory plus a small app.R that sources it, so the browser version is built
# from exactly what the package ships and cannot drift from it. The start-up prelude and the bundle hint are the
# fixes found by the item-15 spike (tools/webr-spike/make_app.R explains each).
# Usage: Rscript tools/pages/make_app.R <out_dir> [variant]   variant: default | noprelude | hello | instrumented (the last three are for the memory
# measurements in .github/workflows/memory-spike.yml, not for publishing: "noprelude" breaks the mixed-model designs, "hello" is a
# one-line Shiny page that shows the memory floor of the browser runtime itself).
args <- commandArgs(trailingOnly = TRUE)
out <- if (length(args) >= 1) args[1] else "pages_app"
variant <- if (length(args) >= 2) args[2] else "default"
if (variant == "hello") {
  unlink(out, recursive = TRUE); dir.create(out, recursive = TRUE)
  writeLines(c("library(shiny)", "shinyApp(fluidPage(h3(\"Hello memory probe\")), function(input, output, session) {})"), file.path(out, "app.R"))
  cat("Wrote", out, "(hello variant)\n"); quit(save = "no")
}
unlink(out, recursive = TRUE); dir.create(file.path(out, "R"), recursive = TRUE)
invisible(file.copy(list.files("R", full.names = TRUE), file.path(out, "R")))

# Shinylive bundles the packages it finds by scanning the sources for pkg:: references. MASS (needed by lme4) is not
# found that way and webR's own library has MASS without its compiled part, so name it in a branch that never runs.
writeLines(c("# bundle hints for shinylive's package scan; never executed",
             "if (FALSE) {", "  MASS::mvrnorm", "  nlme::lme", "}"),
           file.path(out, "R", "zz_bundle_hints.R"))

# In webR, MASS and lme4 must be loaded first (loaded late, their compiled parts fail to load); the font is a local
# stack, so no download is needed to render the page.
prelude <- if (variant == "noprelude") character() else c(
  "if (identical(Sys.info()[['sysname']], 'Emscripten') && requireNamespace('webr', quietly = TRUE)) {",
  "  try(webr::install('MASS', quiet = TRUE), silent = TRUE)",
  "  message('PRELUDE load MASS: ', tryCatch({ loadNamespace('MASS'); 'ok' }, error = function(e) conditionMessage(e)))",
  "  message('PRELUDE load lme4: ', tryCatch({ loadNamespace('lme4'); 'ok' }, error = function(e) conditionMessage(e)))",
  "}")
stage <- function(name) if (variant == "instrumented") sprintf("message('MEMSTAGE %s ', paste(round(gc()[, 6], 1), collapse = ' '))", name) else character()
writeLines(c(
  "# generated by tools/pages/make_app.R from the package's R/ directory",
  stage("start"),
  prelude,
  stage("after_prelude"),
  # literal names, not a loop over a variable: shinylive's package scan reads library(<name>) and would treat a variable
  # called p as a package called "p"
  "suppressPackageStartupMessages(library(shiny))",
  stage("after_shiny"),
  "suppressPackageStartupMessages(library(bslib))",
  stage("after_bslib"),
  "for (f in sort(list.files('R', pattern = '[.]R$', full.names = TRUE))) {",
  "  r <- try(source(f, local = FALSE), silent = TRUE)",
  "  if (inherits(r, 'try-error')) message('SOURCE FAILED: ', f, ': ', conditionMessage(attr(r, 'condition')))",
  "}",
  stage("after_source"),
  if (variant == "instrumented") "app_obj <- epidemiologicasuite_app()" else "app_obj <- epidemiologicasuite_app()",
  stage("after_app_object"),
  if (variant == "instrumented") "invisible(htmltools::renderTags(attr(app_obj, 'ui_tags')))" else character(),
  stage("after_render_page_with_theme"),
  "app_obj"
), file.path(out, "app.R"))
cat(sprintf("Wrote %s (%d R files)\n", out, length(list.files(file.path(out, "R")))))
