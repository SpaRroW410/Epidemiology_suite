evpi_content <- list(
  evpi = list(
    title = "Expected Value of Perfect Information (EVPI)",
    formula_latex = paste0(
      "$$EVPI = \\sigma \\, \\phi\\!\\left(\\frac{\\mu}{\\sigma}\\right) - ",
      "\\mu \\, \\Phi\\!\\left(-\\frac{\\mu}{\\sigma}\\right)$$",
      "$$\\mu = \\text{prior mean incremental net benefit}, \\ ",
      "\\sigma = \\text{prior SD of incremental net benefit}$$"
    ),
    backend = "closed-form reimplementation (unit normal loss integral)"
  ),
  evsi = list(
    title = "Expected Value of Sample Information (EVSI) and Optimal Sample Size (ENBS)",
    formula_latex = paste0(
      "$$\\text{Var}_{\\text{pre-posterior}}(n) = \\sigma^2 - ",
      "\\left(\\frac{1}{\\sigma^2} + \\frac{n}{\\sigma_e^2}\\right)^{-1}$$",
      "$$EVSI(n) = \\sqrt{\\text{Var}_{\\text{pre-posterior}}(n)} \\, \\phi\\!\\left(\\frac{\\mu}{\\sqrt{\\text{Var}_{\\text{pre-posterior}}(n)}}\\right) - ",
      "\\mu \\, \\Phi\\!\\left(-\\frac{\\mu}{\\sqrt{\\text{Var}_{\\text{pre-posterior}}(n)}}\\right)$$",
      "$$ENBS(n) = N_{pop} \\times EVSI(n) - c_{fixed} - n \\times c_{patient}$$"
    ),
    backend = "closed-form reimplementation (normal-normal pre-posterior variance)"
  ),
  shared = list(
    explanation = paste(
      "**Value of Information (VOI)** answers a different question from",
      "every other calculator in this app: not \"how big does my planned",
      "study need to be to detect an assumed effect,\" but \"is it even",
      "worth running more research at all, and if so, how much?\" -- the",
      "standard framework in health-economic (cost-effectiveness) decision",
      "analysis for deciding whether, and how large, a further study",
      "should be.",
      "",
      "**This needs a different kind of input.** Instead of an assumed",
      "effect size and variance, VOI needs the DECISION UNCERTAINTY",
      "itself, summarized as the **incremental net benefit (INB)** --",
      "willingness-to-pay per unit of effect, times the incremental",
      "effect, minus the incremental cost, of one treatment vs. another --",
      "expressed as a mean and SD. This mean/SD would normally come from",
      "an existing **probabilistic sensitivity analysis (PSA)** of a",
      "decision-analytic (e.g. Markov cohort) model: thousands of Monte",
      "Carlo draws of costs and effects under parameter uncertainty,",
      "summarized down to the INB's own mean and SD. This calculator",
      "does not build that decision model for you -- it takes the",
      "already-summarized INB mean/SD as given.",
      "",
      "- **mean_inb** - the expected incremental net benefit (positive",
      "  favors adopting the new treatment/technology).",
      "- **sd_inb** - the SD of the incremental net benefit across the",
      "  PSA, capturing how uncertain the decision currently is.",
      "- **Population** - the number of current and future patients, over",
      "  the technology's relevant decision horizon, who would benefit",
      "  from resolving this uncertainty; leave at 1 for a per-patient",
      "  value. This matters a great deal: a small per-patient EVPI can",
      "  still justify a large trial once multiplied across a large",
      "  future patient population.",
      "",
      "**EVPI** (Expected Value of PERFECT Information) is the maximum",
      "possible value of ANY further research -- an upper bound, useful",
      "on its own as an \"is it even worth looking\" screening step, since",
      "no real (finite) study can be worth more than this.",
      "",
      "**EVSI** (Expected Value of SAMPLE Information) is the value of a",
      "SPECIFIC proposed study of size n, always less than or equal to",
      "EVPI, and increasing toward it as n grows. This calculator's EVSI",
      "covers the case where the decision uncertainty is driven by a",
      "single normally-distributed, known-SD outcome measured on n",
      "patients (`sampling_sd` is that per-patient outcome SD) --",
      "`voi`'s own `study = \"normal_known\"` built-in case, the simplest",
      "and most tractable of its supported study designs.",
      "",
      "**ENBS** (Expected Net Benefit of Sampling) subtracts the cost of",
      "actually running the study (a fixed setup cost plus a per-patient",
      "cost) from the population-scaled EVSI, and this calculator finds",
      "the sample size that MAXIMIZES it -- the closest VOI analogue to",
      "the \"required sample size\" every other calculator in this app",
      "reports, but here it's an economically OPTIMAL size (a tradeoff),",
      "not a size guaranteeing a target power.",
      sep = "\n"
    ),
    worked_example = paste(
      "**EVPI**: mean INB = 100 (monetary units), SD = 200 -> EVPI = 39.56",
      "per patient -- exactly matching real `voi::evpi()`'s own",
      "Monte-Carlo estimate once it's run with enough replicates to",
      "converge, and an independent numerical integration of the same",
      "formula, bit-for-bit.",
      "",
      "**EVSI**: the same decision, plus a proposed study measuring an",
      "outcome with per-patient SD = 300, sample size n = 200 -> EVSI =",
      "39.17 per patient -- exactly matching an independent numerical",
      "integration (bypassing the `voi` package entirely), and closely",
      "matching `voi::evsi(study = \"normal_known\")`'s own",
      "regression-based estimate once its own internal simulation size is",
      "large enough to converge.",
      "",
      "**ENBS-optimal sample size**: mean INB = 1,000, SD = 3,000,",
      "per-patient outcome SD = 8,000, population = 50,000 patients, cost",
      "= 500 per patient sampled -> this calculator recommends n = 629,",
      "achieving an expected net benefit of sampling of about 37.5",
      "million (monetary units) -- compare to the maximum-possible value",
      "of perfect information, population EVPI = 38.1 million, showing",
