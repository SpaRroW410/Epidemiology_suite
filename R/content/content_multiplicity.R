  fdr = list(
    title = "FDR (Benjamini-Hochberg)-Controlled Sample Size, Two Independent Means",
    formula_latex = paste0(
      "$$\\alpha^{*} = \\frac{q \\cdot m_1 \\cdot \\text{power}}{m_0 (1-q)}, ",
      "\\qquad m_1 = \\pi_1 m,\\ m_0 = m - m_1$$",
      "$$n \\text{ solved from } \\alpha^{*}, \\text{power, and Cohen's } d ",
      "\\text{ via the ordinary two-sample } t\\text{-test}$$"
    ),
    explanation = paste(
      "Bonferroni/Sidak above control the family-wise error rate (the",
      "chance of ANY false positive among m tests). This design instead",
      "controls the FALSE DISCOVERY RATE (FDR) -- the expected PROPORTION",
      "of rejected tests that are false positives -- at a target level q,",
      "when a known/assumed fraction pi1 of the m tests are truly",
      "non-null (e.g. m outcome variables, only some of which truly",
      "differ between groups). Because FDR control tolerates a controlled",
      "fraction of false positives among the rejections rather than",
      "trying to prevent any at all, it typically needs a SMALLER sample",
      "size than the always-conservative Bonferroni correction for the",
      "same m, when pi1 is not too small.",
      "",
      "- **d** - Cohen's d effect size for the truly non-null tests (a",
      "  two-sample means comparison).",
      "- **m** - total number of planned simultaneous tests.",
      "- **pi1** - the assumed proportion of the m tests that are truly",
      "  non-null (e.g. 0.1 if roughly 10% of outcomes are expected to",
      "  show a real effect). m1 = pi1*m truly non-null, m0 = m - m1",
      "  truly null.",
      "- **FDR level (q)** - the target false discovery rate, typically",
      "  0.05-0.10.",
      "- **power** - here, the target AVERAGE power: the expected",
      "  proportion of the m1 truly non-null tests that get detected.",
      "",
      "Applying the Benjamini & Hochberg (1995) procedure at level q is,",
      "for a large number of tests, well approximated by rejecting every",
      "test at a fixed per-test threshold alpha* solving FDR = E[false",
      "rejections] / E[total rejections] = (m0 alpha*) / (m0 alpha* + m1",
      "power) -- solving this equation directly for alpha* gives the",
      "closed form above, then the ordinary two-sample t-test sample size",
      "at that (typically much smaller, hence larger-n-permitting)",
      "alpha* and the target power is found the same way this app's",
      "other means-comparison designs already do.",
      sep = "\n"
    ),
    worked_example = paste(
      "This closed form was independently derived from the standard",
